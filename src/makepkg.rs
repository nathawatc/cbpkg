use crate::error::AppError;
use crate::profile::TargetProfile;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

#[derive(Debug, Clone)]
pub struct MakepkgBuildOptions {
    pub syncdeps: bool,
    pub clean: bool,
    pub cleanbuild: bool,
    pub force: bool,
    pub noconfirm: bool,
}

impl Default for MakepkgBuildOptions {
    fn default() -> Self {
        Self {
            syncdeps: true,
            clean: true,
            cleanbuild: true,
            force: true,
            noconfirm: false,
        }
    }
}

pub fn find_makepkg() -> Result<PathBuf, AppError> {
    if let Ok(path) = std::env::var("PATH") {
        for dir in std::env::split_paths(&path) {
            let candidate = dir.join("makepkg");
            if candidate.is_file() {
                return Ok(candidate);
            }
        }
    }
    Err(AppError::MakepkgNotFound)
}

pub fn check_makepkg_supports_packagecarch(makepkg_path: &Path) -> Result<bool, AppError> {
    if let Ok(content) = fs::read_to_string(makepkg_path)
        && content.contains("PACKAGECARCH")
    {
        return Ok(true);
    }

    // Also check libmakepkg scripts if present
    let lib_dir = Path::new("/usr/share/makepkg");
    if lib_dir.is_dir()
        && let Ok(entries) = fs::read_dir(lib_dir)
    {
        for entry in entries.flatten() {
            let p = entry.path();
            if p.is_file()
                && let Ok(content) = fs::read_to_string(&p)
                && content.contains("PACKAGECARCH")
            {
                return Ok(true);
            }
        }
    }

    Ok(false)
}

pub fn generate_makepkg_config(
    base_config: &Path,
    target: &TargetProfile,
    out_path: &Path,
) -> Result<(), AppError> {
    let base_content =
        fs::read_to_string(base_config).map_err(|e| AppError::BaseConfigUnreadable {
            path: base_config.to_path_buf(),
            source: e,
        })?;

    let overrides = format!(
        r#"

#########################################################################
# Temporary profile generated by cbpkg
#########################################################################
CARCH="x86_64"
CHOST="x86_64-pc-linux-gnu"
PACKAGECARCH="{package_carch}"

CFLAGS="{cflags}"
CXXFLAGS="{cxxflags}"

export GOAMD64="{goamd64}"
export RUSTFLAGS="{rustflags}"

# Ensure makepkg --packagelist reflects PACKAGECARCH
if (( PACKAGELIST )); then
    if [[ -n "$PACKAGECARCH" ]]; then
        IGNOREARCH=1
        CARCH="$PACKAGECARCH"
    fi
fi
"#,
        package_carch = target.package_carch(),
        cflags = target.cflags(),
        cxxflags = target.cxxflags(),
        goamd64 = target.goamd64_str(),
        rustflags = target.rustflags(),
    );

    let mut combined = base_content;
    combined.push_str(&overrides);

    fs::write(out_path, combined).map_err(AppError::TempConfigCreate)?;

    Ok(())
}

pub fn get_planned_packages(
    makepkg_path: &Path,
    config_path: &Path,
    working_dir: &Path,
) -> Result<Vec<PathBuf>, AppError> {
    let output = Command::new(makepkg_path)
        .arg("--packagelist")
        .arg("--config")
        .arg(config_path)
        .current_dir(working_dir)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
        .map_err(|e| AppError::ProcessExecution {
            cmd: "makepkg --packagelist".to_string(),
            source: e,
        })?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr).to_string();
        return Err(AppError::MakepkgPackagelistFailed(stderr));
    }

    let stdout = String::from_utf8_lossy(&output.stdout);
    let mut packages = Vec::new();
    for line in stdout.lines() {
        let trimmed = line.trim();
        if !trimmed.is_empty() {
            packages.push(PathBuf::from(trimmed));
        }
    }

    if packages.is_empty() {
        return Err(AppError::NoPackageOutputs);
    }

    Ok(packages)
}

pub fn execute_build(
    makepkg_path: &Path,
    config_path: &Path,
    working_dir: &Path,
    options: &MakepkgBuildOptions,
) -> Result<(), AppError> {
    let mut cmd = Command::new(makepkg_path);
    cmd.current_dir(working_dir)
        .arg("--config")
        .arg(config_path);

    if options.cleanbuild {
        cmd.arg("--cleanbuild");
    }
    if options.clean {
        cmd.arg("--clean");
    }
    if options.force {
        cmd.arg("--force");
    }
    if options.syncdeps {
        cmd.arg("--syncdeps");
    }
    if options.noconfirm {
        cmd.arg("--noconfirm");
    }

    // Direct user terminal output
    cmd.stdout(Stdio::inherit());
    cmd.stderr(Stdio::inherit());

    let status = cmd.status().map_err(|e| AppError::ProcessExecution {
        cmd: "makepkg build".to_string(),
        source: e,
    })?;

    if !status.success() {
        return Err(AppError::ProcessFailed {
            cmd: "makepkg".to_string(),
            exit_code: status.code(),
            stderr: "makepkg build process returned an error".to_string(),
        });
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cpu::CpuFeatures;
    use crate::profile::BuildProfile;

    #[test]
    fn test_generate_config_generic() {
        let temp_dir = tempfile::tempdir().unwrap();
        let base_conf = temp_dir.path().join("base.conf");
        let out_conf = temp_dir.path().join("out.conf");
        fs::write(&base_conf, "PKGEXT='.pkg.tar.zst'\n").unwrap();

        let cpu = CpuFeatures::default();
        let target = TargetProfile::new(BuildProfile::Generic, &cpu);
        generate_makepkg_config(&base_conf, &target, &out_conf).unwrap();

        let content = fs::read_to_string(&out_conf).unwrap();
        assert!(content.contains("PKGEXT='.pkg.tar.zst'"));
        assert!(content.contains("PACKAGECARCH=\"x86_64\""));
        assert!(content.contains("-march=x86-64 -mtune=generic"));
        assert!(content.contains("GOAMD64=\"v1\""));
        assert!(content.contains("target-cpu=x86-64"));
    }

    #[test]
    fn test_generate_config_native() {
        let temp_dir = tempfile::tempdir().unwrap();
        let base_conf = temp_dir.path().join("base.conf");
        let out_conf = temp_dir.path().join("out.conf");
        fs::write(&base_conf, "PKGEXT='.pkg.tar.zst'\n").unwrap();

        let cpu = CpuFeatures::new(vec![
            "cx16", "lahf_lm", "popcnt", "pni", "ssse3", "sse4_1", "sse4_2", "avx", "avx2", "bmi1",
            "bmi2", "f16c", "fma", "abm", "movbe", "xsave",
        ]);
        let target = TargetProfile::new(BuildProfile::Native, &cpu);
        generate_makepkg_config(&base_conf, &target, &out_conf).unwrap();

        let content = fs::read_to_string(&out_conf).unwrap();
        assert!(content.contains("PACKAGECARCH=\"x86_64_native\""));
        assert!(content.contains("-march=native -mtune=native"));
        assert!(content.contains("GOAMD64=\"v3\""));
        assert!(content.contains("target-cpu=native"));
    }

    #[test]
    fn test_generate_config_v3() {
        let temp_dir = tempfile::tempdir().unwrap();
        let base_conf = temp_dir.path().join("base.conf");
        let out_conf = temp_dir.path().join("out.conf");
        fs::write(&base_conf, "").unwrap();

        let cpu = CpuFeatures::default();
        let target = TargetProfile::new(BuildProfile::V3, &cpu);
        generate_makepkg_config(&base_conf, &target, &out_conf).unwrap();

        let content = fs::read_to_string(&out_conf).unwrap();
        assert!(content.contains("PACKAGECARCH=\"x86_64_v3\""));
        assert!(content.contains("-march=x86-64-v3 -mtune=generic"));
        assert!(content.contains("-mpclmul"));
        assert!(content.contains("GOAMD64=\"v3\""));
        assert!(content.contains("target-cpu=x86-64-v3"));
    }
}
